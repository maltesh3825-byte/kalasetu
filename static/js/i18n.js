let currentLanguage = localStorage.getItem('kalakriti_language') || 'en';

function setLanguage(lang) {
  if (!translations[lang]) lang = 'en';
  currentLanguage = lang;
  localStorage.setItem('kalakriti_language', lang);
  document.documentElement.lang = lang;
  
  const dict = translations[lang] || translations.en;
  const fallback = translations.en;

  // 1. Update text content for all elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const text = dict[key] || fallback[key];
    if (text) {
      el.textContent = text;
    }
  });

  // 2. Update placeholder attributes
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    const text = dict[key] || fallback[key];
    if (text) {
      el.setAttribute('placeholder', text);
    }
  });

  // 3. Update title attributes
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    const text = dict[key] || fallback[key];
    if (text) {
      el.setAttribute('title', text);
    }
  });

  // 4. Update the language select dropdown value if present
  const languageSelect = document.getElementById('languageSelect');
  if (languageSelect && languageSelect.value !== lang) {
    languageSelect.value = lang;
  }

  // 5. Update main desktop navigation tab labels
  const navMap = {
    home: dict.nav_home,
    studio: dict.nav_studio,
    marketplace: dict.nav_market,
    institutional: dict.nav_bulk,
    account: dict.nav_account
  };
  Object.entries(navMap).forEach(([tabKey, label]) => {
    if (label) {
      document.querySelectorAll(`[data-tab-target="${tabKey}"] span:last-child`).forEach(span => {
        span.textContent = label;
      });
    }
  });

  // 6. Update account sub-view buttons
  document.querySelectorAll('[data-account-view]').forEach(btn => {
    const viewKey = `account_${btn.dataset.accountView}`;
    const label = dict[viewKey] || fallback[viewKey];
    if (label) {
      if (btn.dataset.accountView === 'notifications') {
        const badge = btn.querySelector('#notificationCountBadge');
        btn.childNodes.forEach(node => {
          if (node.nodeType === 3 && node.textContent.trim()) {
            node.textContent = label;
          }
        });
        if (badge) btn.appendChild(badge);
      } else {
        btn.textContent = label;
      }
    }
  });

  // 7. Notify app.js to re-render dynamic content (categories, products, orders)
  if (typeof window.onLanguageChanged === 'function') {
    try {
      window.onLanguageChanged(lang);
    } catch (err) {
      console.warn('onLanguageChanged error:', err);
    }
  }
}

function toggleLanguage() {
  const nextLang = currentLanguage === 'en' ? 'hi' : 'en';
  setLanguage(nextLang);
}

function t(key) {
  return (translations[currentLanguage] && translations[currentLanguage][key]) ||
         (translations.en && translations.en[key]) ||
         key;
}

// Initialise language listener on page load
if (typeof window !== 'undefined') {
  window.addEventListener('DOMContentLoaded', () => {
    const select = document.getElementById('languageSelect');
    if (select) {
      select.value = currentLanguage;
      select.addEventListener('change', (e) => {
        setLanguage(e.target.value);
      });
    }
    setLanguage(currentLanguage);
  });
}
